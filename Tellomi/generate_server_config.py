#!/usr/bin/env python3
"""Regenerate the ObjC string embedded from Tellomi/tellomi-server.json.

The JSON file is the only copy of the server address, port and RSA key.
MtProtoKit cannot read that file at runtime (it is not in the app bundle),
so this script writes the same bytes into a private header the library
compiles in. Run it after every edit:

    python3 Tellomi/generate_server_config.py

Tellomi/check_server_config.py fails when the header and the JSON disagree.
"""

import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[1]
JSON_PATH = ROOT / "Tellomi" / "tellomi-server.json"
HEADER_PATH = ROOT / "submodules" / "MtProtoKit" / "Sources" / "TellomiServerConfigJSON.h"


def objc_string_literal(text: str) -> str:
    out = []
    for ch in text:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\r":
            out.append("\\r")
        else:
            out.append(ch)
    return "".join(out)


def header_text(json_text: str) -> str:
    literal = objc_string_literal(json_text)
    return (
        "// Generated by Tellomi/generate_server_config.py from Tellomi/tellomi-server.json.\n"
        "// Do not edit. Change the JSON, then rerun the generator.\n"
        f'#define TELLOMI_SERVER_CONFIG_JSON @"{literal}"\n'
    )


def main() -> None:
    json_text = JSON_PATH.read_text(encoding="utf-8")
    # Reject a file that is not the canonical dump, so the embedded copy and
    # the file cannot drift by whitespace alone.
    obj = json.loads(json_text)
    canonical = json.dumps(obj, indent=2, ensure_ascii=True) + "\n"
    if json_text != canonical:
        JSON_PATH.write_text(canonical, encoding="utf-8")
        json_text = canonical
    HEADER_PATH.write_text(header_text(json_text), encoding="utf-8")
    print(f"wrote {HEADER_PATH.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
